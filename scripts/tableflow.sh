#!/usr/bin/env bash
# Tableflow (Kafka topic -> Iceberg/Delta in your S3 bucket), non-interactive.
#
#   tableflow.sh preflight                AWS login + CLI present (fails fast, before provisioning)
#   tableflow.sh up                       AWS bucket + IAM role + provider integration (2-phase Terraform)
#   tableflow.sh status                   what is deployed, trust-policy state, enabled topics
#   tableflow.sh enable <topic> [FORMAT]  enable Tableflow on a topic (ICEBERG default, or DELTA)
#   tableflow.sh disable <topic> [--force]   (--force skips the CLI confirmation)
#
# `up` never prompts. It is the single implementation behind both `make tableflow-up`
# and the Tableflow step of startup-demo.sh. Re-running keeps the phase-2
# trust-policy values already in terraform.tfvars instead of regenerating them
# (which would flip the trust policy back and forth).

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

need terraform; need jq

cc_deployed() { tf_out "$TF_CC" environment_id >/dev/null || die "Confluent infrastructure not deployed — run: make infra"; }
tf_deployed() { [ -n "$(tf_out "$TF_TF" s3_bucket_name || true)" ] || die "Tableflow AWS infrastructure not deployed — run: make tableflow-up"; }

# Confluent CLI auth: honour an existing `confluent login`; otherwise fall back
# to the Cloud API key Terraform already uses (the CLI reads these two env vars).
cli_env() {
  need confluent
  load_cc_creds
  export CONFLUENT_CLOUD_API_KEY="${CONFLUENT_CLOUD_API_KEY:-${TF_VAR_confluent_cloud_api_key:-}}"
  export CONFLUENT_CLOUD_API_SECRET="${CONFLUENT_CLOUD_API_SECRET:-${TF_VAR_confluent_cloud_api_secret:-}}"
  ENV_ID="$(tf_out "$TF_CC" environment_id)"
  CLUSTER_ID="$(tf_out "$TF_CC" kafka_cluster_id)"
}

aws_region_for_cluster() {
  local r; r="$(tf_out "$TF_CC" kafka_cluster_region || true)"        # e.g. AWS/eu-west-1
  if [[ "$r" == AWS/* ]]; then echo "${r#AWS/}"; return; fi
  r="${AWS_REGION:-${AWS_DEFAULT_REGION:-$(aws configure get region 2>/dev/null || true)}}"
  warn "could not read cluster region from Terraform — using '${r:-us-east-1}'" >&2
  echo "${r:-us-east-1}"
}

write_tfvars() {  # $1 region  $2 role_arn(optional)  $3 external_id(optional)
  local f="$TF_TF/terraform.tfvars" key secret
  key="$(tf_out "$TF_CC" mcp_server_env_config | sed -n 's/^CONFLUENT_CLOUD_API_KEY=//p' | head -1 || true)"
  secret="$(tf_out "$TF_CC" mcp_server_env_config | sed -n 's/^CONFLUENT_CLOUD_API_SECRET=//p' | head -1 || true)"
  [ -n "$key" ] && [ -n "$secret" ] || die "could not read the Confluent Cloud API key from Terraform outputs (mcp_server_env_config)"
  {
    echo "# Generated by scripts/tableflow.sh — safe to delete, 'make tableflow-up' recreates it"
    echo "aws_region                  = \"$1\""
    echo "confluent_cloud_api_key     = \"$key\""
    echo "confluent_cloud_api_secret  = \"$secret\""
    echo "confluent_environment_id    = \"$(tf_out "$TF_CC" environment_id)\""
    echo "confluent_cluster_id        = \"$(tf_out "$TF_CC" kafka_cluster_id)\""
    echo "create_provider_integration = true"
    # One suffix per demo: reuse the Confluent deployment's, when it exposes one.
    local suffix; suffix="$(tf_out "$TF_CC" name_suffix || true)"
    [ -z "$suffix" ] || echo "name_suffix                 = \"$suffix\""
    if [ -n "${2:-}" ] && [ -n "${3:-}" ]; then
      echo "# Phase 2: trust policy"
      echo "confluent_provider_integration_role_arn = \"$2\""
      echo "confluent_external_id                   = \"$3\""
    fi
  } > "$f"
  chmod 600 "$f"
}

# Value of a phase-2 variable already present (uncommented) in terraform.tfvars.
existing_var() {
  [ -f "$TF_TF/terraform.tfvars" ] || return 0     # first run: nothing to preserve (must not trip set -e)
  sed -n "s/^$1[[:space:]]*=[[:space:]]*\"\(.*\)\"/\1/p" "$TF_TF/terraform.tfvars" | head -1
}

# Needs a working AWS session. With none and no AWS_PROFILE, try the first profile in ~/.aws/credentials.
ensure_aws_auth() {
  need aws
  if ! aws sts get-caller-identity >/dev/null 2>&1 && [ -z "${AWS_PROFILE:-}" ] && [ -f "$HOME/.aws/credentials" ]; then
    local first; first="$(grep '^\[' "$HOME/.aws/credentials" | head -1 | tr -d '[]' || true)"
    if [ -n "$first" ] && aws sts get-caller-identity --profile "$first" >/dev/null 2>&1; then
      export AWS_PROFILE="$first"; info "no AWS_PROFILE set — using profile '$first'"
    fi
  fi
  aws sts get-caller-identity >/dev/null 2>&1 \
    || die "AWS auth failed. Authenticate first (Confluent: your 'assume <role>' command; SSO: 'aws sso login --profile <p>'; or 'aws configure')"
  ok "AWS identity: $(aws sts get-caller-identity --query Arn --output text)"
}

# Run BEFORE anything is provisioned, so a missing AWS login fails in seconds, not after 10 minutes of Confluent.
cmd_preflight() {
  ensure_aws_auth
  need confluent    # used to enable/disable Tableflow topics from scripts (reset, tableflow-enable)
  ok "ready to prepare Tableflow storage"
}

cmd_up() {
  cc_deployed; ensure_aws_auth

  local region role ext
  region="$(aws_region_for_cluster)"; ok "S3 bucket region: $region (matches the Kafka cluster)"
  role="$(existing_var confluent_provider_integration_role_arn)"; ext="$(existing_var confluent_external_id)"

  write_tfvars "$region" "$role" "$ext"
  terraform -chdir="$TF_TF" init -input=false >/dev/null
  info "phase 1: S3 bucket, IAM role, provider integration"
  terraform -chdir="$TF_TF" apply -input=false -auto-approve

  local pi status role2 ext2
  pi="$(tf_out "$TF_TF" provider_integration_id || true)"
  case "$pi" in ""|"Not created"|"Manual creation required") die "provider integration was not created — see: terraform -chdir=$TF_TF output" ;; esac
  ok "provider integration: $pi"

  status="$(tf_out "$TF_TF" current_trust_policy_status || true)"
  if [[ "$status" == *deny-all* || "$status" == *"not yet updated"* ]]; then
    role2="$(tf_out "$TF_TF" confluent_role_arn || true)"; ext2="$(tf_out "$TF_TF" confluent_external_id || true)"
    [[ "$role2" == arn:aws:iam::* && -n "$ext2" ]] || die "no valid Confluent role ARN / external ID from the provider integration yet — re-run 'make tableflow-up' in a minute"
    info "phase 2: updating the IAM trust policy for Confluent role $role2"
    write_tfvars "$region" "$role2" "$ext2"
    terraform -chdir="$TF_TF" apply -input=false -auto-approve
  fi
  ok "Tableflow AWS infrastructure ready — enable a topic with: make tableflow-enable TOPIC=<name>"
}

cmd_status() {
  printf '%sAWS side%s\n' "$C_BLD" "$C_OFF"
  if [ -n "$(tf_out "$TF_TF" s3_bucket_name || true)" ]; then
    printf '  S3 bucket         : %s (%s)\n' "$(tf_out "$TF_TF" s3_bucket_name)" "$(tf_out "$TF_TF" s3_bucket_region)"
    printf '  IAM role          : %s\n'      "$(tf_out "$TF_TF" iam_role_arn)"
    printf '  Provider integr.  : %s\n'      "$(tf_out "$TF_TF" provider_integration_id)"
    printf '  Trust policy      : %s\n'      "$(tf_out "$TF_TF" current_trust_policy_status)"
  else
    echo '  not deployed (optional) — make tableflow-up'; return 0
  fi
  echo; printf '%sEnabled topics%s\n' "$C_BLD" "$C_OFF"
  cli_env; confluent tableflow topic list --cluster "$CLUSTER_ID" --environment "$ENV_ID"
}

cmd_enable() {
  local topic="${1:-}" fmt="${2:-ICEBERG}"
  [ -n "$topic" ] || die "usage: tableflow.sh enable <topic> [ICEBERG|DELTA]"
  case "$fmt" in ICEBERG|DELTA) ;; *) die "FORMAT must be ICEBERG or DELTA (got '$fmt')" ;; esac
  cc_deployed; tf_deployed; cli_env
  info "enabling Tableflow on '$topic' as $fmt in s3://$(tf_out "$TF_TF" s3_bucket_name)"
  confluent tableflow topic enable "$topic" \
    --cluster "$CLUSTER_ID" --environment "$ENV_ID" \
    --storage-type BYOS \
    --provider-integration "$(tf_out "$TF_TF" provider_integration_id)" \
    --bucket-name "$(tf_out "$TF_TF" s3_bucket_name)" \
    --table-formats "$fmt"
}

cmd_disable() {
  local topic="${1:-}" force="${2:-}"
  [ -n "$topic" ] || die "usage: tableflow.sh disable <topic> [--force]"
  case "$force" in ""|--force) ;; *) die "unknown option '$force' (only --force)" ;; esac
  cc_deployed; cli_env
  confluent tableflow topic disable "$topic" --cluster "$CLUSTER_ID" --environment "$ENV_ID" $force
}

case "${1:-}" in
  preflight) cmd_preflight ;;
  up)      cmd_up ;;
  status)  cmd_status ;;
  enable)  shift; cmd_enable "$@" ;;
  disable) shift; cmd_disable "$@" ;;
  *)       echo "usage: $0 preflight|up|status|enable <topic> [FORMAT]|disable <topic> [--force]" >&2; exit 2 ;;
esac
